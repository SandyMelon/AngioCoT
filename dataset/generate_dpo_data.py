import os
import json
import argparse
import gc
import torch
from typing import List, Dict
import argparse
from swift.llm import VllmEngine, PtEngine, RequestConfig

# Paths
MODEL_SFT_PATH = "/path/to/your/merged_cot_sft_model"
MODEL_JUDGE_PATH = "/path/to/your/Qwen3-VL-32B-Instruct"

# Candidate cache
INTERMEDIATE_FILE = "/path/to/your/datasets/dpo_candidates.jsonl"

# Judge prompt
JUDGE_SYSTEM_PROMPT = r"""You are a Senior Medical AI Evaluator and Clinical Reasoning Specialist.
Your task is to audit the "Candidate Response" generated by an AI model against the "Ground Truth" (Gold Standard) provided by human experts.

### Evaluation Criteria:
1. **Diagnostic Accuracy**: Does the Candidate's final conclusion/diagnosis match the Ground Truth? (Strict)
2. **Reasoning Logic**: Is the step-by-step medical reasoning in the Candidate scientifically sound and consistent with the visual evidence described in the Ground Truth?
3. **Hallucination Check**: Does the Candidate mention specific pathological features that are explicitly NOT present in the Ground Truth?

### Decision Rules:
- If the Candidate contains **factual errors**, **wrong diagnoses**, or **hallucinated features**: Output [[REJECT]].
- If the Candidate's reasoning is **logically flawed** (even if the final guess is right): Output [[REJECT]].
- If the Candidate is **correct** but phrased differently (synonyms, different sentence structure) or is less detailed but factually accurate: Output [[ACCEPT]].

### Output Format:
Only output **EXACTLY ONE** classification token: [[ACCEPT]] or [[REJECT]]. Do not provide any explanation."""

def generate_all_candidates(all_data, model_path, gpu_id, batch_size) -> List[Dict]:
    """Generate SFT candidates."""
    os.environ["CUDA_VISIBLE_DEVICES"] = str(gpu_id)
    print(f"Generator: {model_path}, GPU {gpu_id}")
    
    # Generator
    try:
        engine = VllmEngine(
            model_path, 
            tensor_parallel_size=1, 
            max_model_len=8196,
            gpu_memory_utilization=0.5
        )
    except Exception as e:
        print(f"vLLM initialization failed: {e}. Using PtEngine.")
        engine = PtEngine(model_path)

    request_config = RequestConfig(
        max_tokens=2048,
        temperature=0.8,
        top_p=0.9,
        repetition_penalty=1.05
    )

    sample_n = 4
    generated_results = []
    total_batches = (len(all_data) + batch_size - 1) // batch_size
    
    print(f"Generating candidates for {len(all_data)} samples.")

    # Save candidates
    with open(INTERMEDIATE_FILE, 'w', encoding='utf-8') as f_inter:
        for i in range(0, len(all_data), batch_size):
            batch_items = all_data[i : i + batch_size]
            infer_inputs = []
            
            for item in batch_items:
                msgs = [m for m in item['messages'] if m['role'] != 'assistant']
                inp = {
                    'messages': msgs,
                    'images': item.get('images', [])
                }
                for _ in range(sample_n):
                    infer_inputs.append(inp)

            try:
                resp_list = engine.infer(infer_inputs, request_config)
                
                current_idx = 0
                for original_item in batch_items:
                    candidates = []
                    for _ in range(sample_n):
                        resp = resp_list[current_idx]
                        response_text = resp.choices[0].message.content
                        candidates.append(response_text)
                        current_idx += 1
                    
                    result_entry = {
                        "meta": original_item,
                        "candidates": candidates
                    }
                    generated_results.append(result_entry)
                    
                    f_inter.write(json.dumps(result_entry, ensure_ascii=False) + '\n')
                    
                f_inter.flush()
                    
            except Exception as e:
                print(f"Generator batch {i + 1}: {e}")

            if (i // batch_size) % 10 == 0:
                print(f"Generator batch {i // batch_size}")

    print(f"Candidates saved: {INTERMEDIATE_FILE}")
    print("Releasing generator.")
    
    del engine
    gc.collect()
    torch.cuda.empty_cache()
    
    return generated_results

def judge_all_candidates(generated_results, output_file, model_path, gpu_id, batch_size):
    """Filter candidates and write preference pairs."""
    os.environ["CUDA_VISIBLE_DEVICES"] = str(gpu_id)
    
    print(f"Judge: {model_path}, GPU {gpu_id}")
    
    engine = VllmEngine(
        model_path, 
        tensor_parallel_size=1, 
        max_model_len=4096,
        gpu_memory_utilization=0.95
    )
    judge_config = RequestConfig(max_tokens=10, temperature=0.0)
    
    print(f"Judging candidates for {len(generated_results)} samples.")
    saved_count = 0

    with open(output_file, 'w', encoding='utf-8') as f_out:
        for i in range(0, len(generated_results), batch_size):
            batch_data = generated_results[i : i + batch_size]
            judge_inputs = []
            judge_meta_map = []
            
            # Reference and candidate
            for res in batch_data:
                meta = res['meta']
                gt_content = meta['messages'][-1]['content']
                user_query = meta['messages'][-2]['content'] if len(meta['messages']) > 1 else ""
                
                for cand in res['candidates']:
                    content_str = (
                        f"## User Question:\n{user_query}\n\n"
                        f"## Ground Truth:\n{gt_content}\n\n"
                        f"## Candidate Answer:\n{cand}\n\n"
                        "Does the Candidate Answer contain logical errors or hallucination compared to Ground Truth?"
                    )
                    msgs = [
                        {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                        {"role": "user", "content": content_str}
                    ]
                    judge_inputs.append({
                        "messages": msgs,
                        "images": [],
                    })
                    judge_meta_map.append({
                        "original_meta": meta,
                        "candidate": cand
                    })
            
            if not judge_inputs:
                continue

            try:
                judge_resps = engine.infer(judge_inputs, judge_config)
                
                # Keep rejected candidates
                for idx, resp in enumerate(judge_resps):
                    judgement = resp.choices[0].message.content
                    if "[[REJECT]]" in judgement:
                        meta = judge_meta_map[idx]['original_meta']
                        candidate = judge_meta_map[idx]['candidate']
                        
                        dpo_entry = {
                            "messages": meta['messages'],
                            "rejected_response": candidate,
                            "images": meta.get('images', [])
                        }
                        f_out.write(json.dumps(dpo_entry, ensure_ascii=False) + '\n')
                        saved_count += 1
                
                f_out.flush()
                
            except Exception as e:
                 print(f"Judge batch {i}: {e}")

            if (i // batch_size) % 5 == 0:
                print(f"Judge batch {i // batch_size}; pairs: {saved_count}")

    print(f"DPO pairs saved: {saved_count}")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input_file", type=str, default="/path/to/your/datasets/cot_sft_train.jsonl")
    parser.add_argument("--output_file", type=str, default="/path/to/your/datasets/dpo_train.jsonl")
    parser.add_argument("--generator_batch_size", type=int, default=64)
    parser.add_argument("--judge_batch_size", type=int, default=16)
    args = parser.parse_args()

    # Generate or load candidates
    intermediate_results = []
    
    if os.path.exists(INTERMEDIATE_FILE):
        print(f"Loading candidates: {INTERMEDIATE_FILE}")
        with open(INTERMEDIATE_FILE, 'r', encoding='utf-8') as f:
            for line in f:
                if line.strip():
                    intermediate_results.append(json.loads(line))
    else:
        all_data = []
        print(f"Loading data: {args.input_file}")
        with open(args.input_file, 'r', encoding='utf-8') as f:
            for line in f:
                if line.strip():
                    item = json.loads(line)
                    msgs = item['messages']
                    gt_content = msgs[-1]['content'] if msgs[-1]['role'] == 'assistant' else ""
                    all_data.append({
                        "messages": msgs,
                        "images": item.get('images', []),
                        "gt_content": gt_content
                    })
        
        print(f"Samples: {len(all_data)}")
        
        intermediate_results = generate_all_candidates(
            all_data, 
            MODEL_SFT_PATH, 
            gpu_id=0, 
            batch_size=args.generator_batch_size
        )

    # Judge candidates
    if intermediate_results:
        judge_all_candidates(
            intermediate_results, 
            args.output_file, 
            MODEL_JUDGE_PATH, 
            gpu_id=0, 
            batch_size=args.judge_batch_size
        )
    else:
        print("No candidates found.")

    print("DPO data generation finished.")

if __name__ == "__main__":
    main()
